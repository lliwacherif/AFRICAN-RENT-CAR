export const CURRENCY_RATES: Record<Currency, { rate: number; symbol: string; label: string }> = {
  TND: { rate: 1, symbol: 'TND', label: 'Dinar Tunisien' },
  EUR: { rate: 0.298, symbol: '€', label: 'Euro' },
  USD: { rate: 0.323, symbol: '$', label: 'US Dollar' },
};

export function formatPrice(amountInTND: number, currency: Currency): string {
  const { rate, symbol } = CURRENCY_RATES[currency];
  const converted = Math.round(amountInTND * rate);
  if (currency === 'EUR') return `${converted} €`;
  if (currency === 'USD') return `$${converted}`;
  return `${converted} TND`;
}

